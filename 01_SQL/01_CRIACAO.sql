--CRIANDO TRIGGER

CREATE TRIGGER TGR_ALUNO_AULA_COLETIVA_CAPACIDADE
ON ALUNO_AULA_COLETIVA 
AFTER INSERT 
AS
BEGIN
	SET NOCOUNT ON

	IF EXISTS 
	(
		SELECT 1 FROM AULA_COLETIVA AS AC
		INNER JOIN 
			(
			SELECT ID_AULA, COUNT(*) AS TOTAL_INSCRITOS
			FROM ALUNO_AULA_COLETIVA
			WHERE ID_AULA IN (SELECT ID_AULA FROM inserted)
			GROUP BY ID_AULA
			)
		AS CONTAGEM ON CONTAGEM.ID_AULA = AC.ID_AULA
		WHERE CONTAGEM.TOTAL_INSCRITOS > AC.CAPACIDADE_MAXIMA
	)
	BEGIN
		ROLLBACK TRANSACTION
		RAISERROR ('Capacidade máxima da aula coletiva excedida.',16,1)
		RETURN
	END;
END;
GO

-- CRIANDO VIEWS DE IDADES

CREATE VIEW VW_ALUNO_COM_IDADE AS
SELECT ID_ALUNO,
       NOME_ALUNO,
       SOBRENOME_ALUNO,
       DATA_NASCIMENTO_ALUNO,
       DATEDIFF(YEAR, DATA_NASCIMENTO_ALUNO, GETDATE())
       - CASE WHEN 
				DATEADD(YEAR, DATEDIFF(YEAR, DATA_NASCIMENTO_ALUNO, GETDATE()), DATA_NASCIMENTO_ALUNO) --DATA DE ANIVERSARIO
				> CAST(GETDATE() AS DATE) -- DATA ATUAL
         THEN 1 ELSE 0 END AS IDADE_ALUNO
FROM ALUNO;
GO

CREATE VIEW VW_INSTRUTOR_COM_IDADE AS
SELECT 
		ID_INSTRUTOR,
		NOME_INSTRUTOR,
		SOBRENOME_INSTRUTOR,
		DATA_NASCIMENTO_INSTRUTOR,
		DATEDIFF(YEAR,DATA_NASCIMENTO_INSTRUTOR,GETDATE())
